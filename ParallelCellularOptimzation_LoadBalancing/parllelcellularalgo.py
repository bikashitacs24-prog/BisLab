import numpy as np


# 1. Problem: Split 100 tasks evenly between Server A and Server B
def load_cost(servers):
  A, B = servers
  return abs((A + B) - 100) + abs(A - B)


# 2. 3x3 Cellular Grid (each cell holds [Server A tasks, Server B tasks])
grid = np.random.uniform(0, 100, (3, 3, 2))

for step in range(25):
  a = 2 - step * (2 / 25)
  next_grid = np.zeros_like(grid)

  for r in range(3):
    for c in range(3):
      neighbors = [
          grid[r, c],
          grid[(r - 1) % 3, c],
          grid[(r + 1) % 3, c],
          grid[r, (c - 1) % 3],
          grid[r, (c + 1) % 3],
      ]
      alpha, beta, delta = sorted(neighbors, key=load_cost)[:3]

      w = grid[r, c]
      m1 = alpha - (2 * a * np.random.rand(2) - a) * abs(
          2 * np.random.rand(2) * alpha - w
      )
      m2 = beta - (2 * a * np.random.rand(2) - a) * abs(
          2 * np.random.rand(2) * beta - w
      )
      m3 = delta - (2 * a * np.random.rand(2) - a) * abs(
          2 * np.random.rand(2) * delta - w
      )
      next_grid[r, c] = (m1 + m2 + m3) / 3

  grid = next_grid

best = min(grid.reshape(-1, 2), key=load_cost)
print("Balanced Load [Server A, Server B]:", np.round(best, 1))