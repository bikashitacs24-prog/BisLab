import numpy as np


# 1. Problem: Find the hidden treasure at (3.5, -2.0)
def distance_to_treasure(pos):
  return (pos[0] - 3.5) ** 2 + (pos[1] + 2.0) ** 2


# 2. Mini GWO (10 wolves, 30 steps)
wolves = np.random.uniform(-10, 10, (10, 2))
alpha = beta = delta = np.zeros(2)

for step in range(30):
  # Sort wolves from best (closest) to worst
  wolves = sorted(wolves, key=distance_to_treasure)
  alpha, beta, delta = wolves[0], wolves[1], wolves[2]

  # Shrink search radius from 2 to 0
  a = 2 - step * (2 / 30)

  # Move every wolf toward the top 3 leaders
  for i in range(10):
    move1 = alpha - (2 * a * np.random.rand(2) - a) * abs(
        2 * np.random.rand(2) * alpha - wolves[i]
    )
    move2 = beta - (2 * a * np.random.rand(2) - a) * abs(
        2 * np.random.rand(2) * beta - wolves[i]
    )
    move3 = delta - (2 * a * np.random.rand(2) - a) * abs(
        2 * np.random.rand(2) * delta - wolves[i]
    )
    wolves[i] = (move1 + move2 + move3) / 3

print("Treasure found at:", np.round(alpha, 3))